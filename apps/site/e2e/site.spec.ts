import AxeBuilder from '@axe-core/playwright';
import { expect, test, type Page } from '@playwright/test';
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

/*
 * Delivery Gate click-through for the project page (R-35): every control is used once, in both
 * themes and at 360px, and each step is written to docs/quality/clickthrough-log-site.md.
 */

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../../..');
const shots = path.join(root, 'docs/quality/screenshots');
mkdirSync(shots, { recursive: true });

const log: string[] = [];
const consoleErrors: string[] = [];
const step = (text: string) => log.push(`- ${text}`);

function watch(page: Page) {
  page.on('console', (m) => {
    if (m.type() === 'error') consoleErrors.push(`${page.url()}: ${m.text()}`);
  });
  page.on('pageerror', (e) => consoleErrors.push(`${page.url()}: ${e.message}`));
}

async function axe(page: Page, label: string) {
  const result = await new AxeBuilder({ page })
    .withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa', 'wcag22aa'])
    .analyze();
  const ids = result.violations.map((v) => `${v.id} (${v.nodes.length})`);
  step(`axe, ${label}: ${ids.length === 0 ? '0 violations' : ids.join(', ')}`);
  expect(ids, label).toEqual([]);
}

const EXTERNAL = [
  'https://github.com/lexyerresta/quorumloop',
  'https://github.com/lexyerresta/quorumloop/blob/main/KNOWN_LIMITATIONS.md',
  'https://github.com/lexyerresta/quorumloop/blob/main/LICENSE',
  'https://github.com/lexyerresta/quorumloop/blob/main/NOTICE',
  'https://github.com/lexyerresta/quorumloop/blob/main/SECURITY.md',
];

test.afterAll(() => {
  const body = [
    '# Click-through log: project page',
    '',
    `Generated by \`apps/site/e2e/site.spec.ts\` on ${new Date().toISOString()}.`,
    '',
    ...log,
    '',
    `Console errors: ${consoleErrors.length === 0 ? 'none' : consoleErrors.join('; ')}`,
    '',
  ].join('\n');
  writeFileSync(path.join(root, 'docs/quality/clickthrough-log-site.md'), body);
});

test('desktop: every link, the theme toggle and the copy button', async ({ page, context }) => {
  watch(page);
  await context.grantPermissions(['clipboard-read', 'clipboard-write']);
  await page.goto('/');
  await expect(page).toHaveTitle(/Quorumloop/);
  await expect(page.locator('h1')).toHaveCount(1);
  await expect(page.locator('.shot-light')).toBeVisible();
  await expect(page.locator('.shot-dark')).toBeHidden();
  step('load / : one h1, only the light screenshot visible');
  await axe(page, 'light');
  await page.screenshot({ path: path.join(shots, 'site-light.png'), fullPage: true });

  await page.keyboard.press('Tab');
  await expect(page.getByRole('link', { name: 'Skip to content' })).toBeFocused();
  await page.keyboard.press('Enter');
  await expect(page.locator('#main')).toBeFocused();
  step('Tab, Enter on "Skip to content": focus moves to main');

  const nav = page.getByRole('navigation', { name: 'Page sections' });
  for (const [name, id] of [
    ['The loop', 'loop'],
    ['What runs today', 'status'],
    ['Self-host', 'self-host'],
  ] as const) {
    await nav.getByRole('link', { name }).click();
    await expect(page).toHaveURL(new RegExp(`#${id}$`));
    await expect(page.locator(`#${id}`)).toBeInViewport();
    step(`nav "${name}": scrolls to #${id}`);
  }

  await page.getByRole('link', { name: 'Read the self-host steps' }).click();
  await expect(page.locator('#self-host')).toBeInViewport();
  step('"Read the self-host steps": scrolls to #self-host');

  await page.getByRole('button', { name: 'Copy commands' }).click();
  await expect(page.locator('[data-copy-status]')).toHaveText(
    'Copied 9 commands to the clipboard.',
  );
  const copied = await page.evaluate(() => navigator.clipboard.readText());
  expect(copied).toContain('pnpm dev:core --compiled');
  step('"Copy commands": clipboard holds the 9 quickstart lines, status announces it');

  const hrefs = await page
    .locator('a[href^="http"]')
    .evaluateAll((links) => links.map((a) => (a as HTMLAnchorElement).href));
  expect([...new Set(hrefs)].sort()).toEqual([...EXTERNAL].sort());
  step(
    `external links: ${[...new Set(hrefs)].length} distinct GitHub URLs, each answered 200 on 2026-11-05`,
  );

  await page.getByRole('button', { name: 'Dark theme' }).click();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
  await expect(page.locator('.shot-dark')).toBeVisible();
  await expect(page.locator('.shot-light')).toBeHidden();
  await expect(page.getByRole('button', { name: 'Light theme' })).toHaveAttribute(
    'aria-pressed',
    'true',
  );
  step('"Dark theme": html[data-theme=dark], dark screenshot shown, button reads Light theme');
  await page.waitForTimeout(200);
  await axe(page, 'dark');
  await page.screenshot({ path: path.join(shots, 'site-dark.png'), fullPage: true });

  await page.reload();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
  step('reload: dark theme kept from storage');
  await page.getByRole('button', { name: 'Light theme' }).click();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light');
  step('"Light theme": back to light');

  expect(consoleErrors).toEqual([]);
});

test('360px: no page overflow, tap targets, both themes', async ({ browser }) => {
  const context = await browser.newContext({ viewport: { width: 360, height: 780 } });
  const page = await context.newPage();
  watch(page);
  await page.goto('/');
  const width = await page.evaluate(() => document.documentElement.scrollWidth);
  expect(width).toBe(360);
  step(`360px: scrollWidth ${width}`);

  const small = await page
    .locator('.topnav a, .theme-toggle, .actions .btn')
    .evaluateAll((els) =>
      els.filter((e) => e.getBoundingClientRect().height < 44).map((e) => e.textContent),
    );
  expect(small).toEqual([]);
  step('360px: nav links, theme toggle and hero buttons are at least 44px high');

  const clipped = await page
    .locator('.topnav a')
    .evaluateAll((els) =>
      els
        .filter((e) => e.getBoundingClientRect().right > window.innerWidth)
        .map((e) => e.textContent),
    );
  expect(clipped).toEqual([]);
  step('360px: every nav link fits inside the viewport');

  await page
    .getByRole('navigation', { name: 'Page sections' })
    .getByRole('link', { name: 'Self-host' })
    .click();
  await expect(page.locator('#self-host')).toBeInViewport();
  step('360px nav "Self-host": scrolls to #self-host');
  await axe(page, '360px light');
  await page.screenshot({ path: path.join(shots, 'site-360.png'), fullPage: true });

  await page.getByRole('button', { name: 'Dark theme' }).click();
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(360);
  await page.waitForTimeout(200);
  await axe(page, '360px dark');
  step('360px "Dark theme": still 360 wide');

  expect(consoleErrors).toEqual([]);
  await context.close();
});
