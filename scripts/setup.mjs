#!/usr/bin/env node
// Generates a `.env` for this checkout from `.env.example` with fresh secrets. It never touches
// a real `.env` without --force, and it never prints a secret value to the terminal.
import { randomBytes } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { ROOT, color, die, log, rootEnvFile } from './lib/workspace.mjs';

const force = process.argv.includes('--force');
const templateFile = path.join(ROOT, '.env.example');

if (!existsSync(templateFile)) {
  die('.env.example is missing', 'restore it from the repository before running setup');
}

if (existsSync(rootEnvFile) && !force) {
  die(
    '.env already exists',
    'pass --force to regenerate it (this rotates every secret and invalidates existing sessions)',
  );
}

const secret = (bytes) => randomBytes(bytes).toString('base64url');

/**
 * Values that must be unique per installation. Anything left as `change-me` is a placeholder
 * that `readEnv()` rejects in production, so it is replaced here rather than left to fail later.
 */
const generated = new Map([
  ['POSTGRES_SUPERUSER_PASSWORD', secret(18)],
  ['POSTGRES_SERVICE_PASSWORD', secret(24)],
  ['REDIS_PASSWORD', secret(18)],
  ['INTERNAL_SHARED_SECRET', randomBytes(32).toString('hex')],
  ['SESSION_SECRET', randomBytes(32).toString('hex')],
  // AES-256-GCM needs exactly 32 bytes, base64 encoded.
  ['SECRET_ENCRYPTION_KEY', randomBytes(32).toString('base64')],
  ['SETUP_BOOTSTRAP_TOKEN', secret(24)],
  // Smoke credentials are generated so the second `pnpm smoke` run can log in. The policy needs
  // mixed case and a digit, so the suffix is fixed rather than random.
  ['SMOKE_EMAIL', 'smoke@quorumloop.local'],
  ['SMOKE_PASSWORD', `Smoke-${secret(12)}-9Z`],
]);

const rewrite = (line) => {
  const trimmed = line.trim();
  if (!trimmed || trimmed.startsWith('#')) {
    return line;
  }
  const separator = trimmed.indexOf('=');
  if (separator <= 0) {
    return line;
  }
  const key = trimmed.slice(0, separator).trim();
  if (generated.has(key)) {
    return `${key}=${generated.get(key)}`;
  }
  // The redis URL embeds the password, so it is rewritten together with it.
  if (key === 'REDIS_URL') {
    return `REDIS_URL=redis://:${generated.get('REDIS_PASSWORD')}@127.0.0.1:6379`;
  }
  return line;
};

const header = [
  '# Generated by `pnpm setup`. Never commit this file; it is ignored by .gitignore.',
  `# Created ${new Date().toISOString()}. Run \`pnpm setup --force\` to rotate the secrets.`,
  '',
];

const template = readFileSync(templateFile, 'utf8').split(/\r?\n/);
const content = [...header, ...template.map(rewrite)].join('\n');

writeFileSync(rootEnvFile, content, { mode: 0o600 });

// A placeholder that survived the rewrite would fail on the next production boot, so the check
// happens here where the fix is obvious.
const remaining = content
  .split('\n')
  .filter((line) => /^[A-Z0-9_]+=change-me/.test(line.trim()))
  .map((line) => line.split('=')[0]);

log.step('Environment ready');
log.ok(`wrote ${path.relative(ROOT, rootEnvFile)} with ${generated.size} generated secrets`);
if (remaining.length > 0) {
  log.warn(
    `placeholders kept (configure these when you need the integration): ${remaining.join(', ')}`,
  );
}
log.info(`the first-run bootstrap token is SETUP_BOOTSTRAP_TOKEN in .env`);

log.step('Next steps');
log.info('1. pnpm infra:up      start postgres, redis and nats');
log.info('2. pnpm db:migrate    create the schema in every service database');
log.info('3. pnpm dev:core      run the core services and the dashboard');
log.info('4. pnpm smoke         verify the running stack end to end');
console.log();
log.info(color.dim('Compose alternative: pnpm compose:core runs the same stack in containers.'));
